using Mic.Orm;
using Mic.Orm.Db;
using Mic.Orm.Db.Model.Upgrades;
using Mic.Orm.Db.Postgres;
using Mic.Orm.Db.Provider;

namespace Mic.Tests.Orm;

// The first step that produces SQL TEXT, and it is verified by comparing that text — which is the whole reason for
// doing it before anything connects to a database.
[TestClass]
public class DdlGenerationTests {
  const string NoServer = "Host=nowhere.invalid;Database=none;Username=none;Password=none";

  private interface IAddress {
    [PrimaryKey] Guid Id { get; set; }
    string City { get; set; }
  }

  [Index("LastName -Rank", IncludeMembers = "City", Filter = "\"LastName\" IS NOT NULL")]
  private interface IPerson {
    [PrimaryKey] Guid Id { get; set; }
    [Size(80)] string LastName { get; set; }
    string? MiddleName { get; set; }
    int Rank { get; set; }
    string City { get; set; }
    [Unique] string Email { get; set; }
    [Auto(AutoType.Identity)] int Seq { get; set; }
    [CascadeDelete] IAddress Address { get; set; }
  }

  private static IReadOnlyList<DdlStatement> Ddl(DbProvider provider, params Type[] types) {
    var app = new EntityApp("App", new Version(1, 0), new EntityAppSettings { DefaultSchema = "app" });
    var module = new EntityModule("M", new Version(1, 0));
    module.RegisterEntities(types.Length > 0 ? types : [typeof(IPerson), typeof(IAddress)]);
    app.AddModule(module);
    app.Settings.IncludeDbInfoModule = false;
    app.TryInit();
    if (app.Initialized)
      AppInitHelper.CreateDatabase(app, new DbSettings(provider, NoServer));
    Assert.IsTrue(app.Initialized, app.Report());
    return new DbDdlBuilder(provider).CreateModel(app.MappedModel());
  }

  private static IReadOnlyList<DdlStatement> Postgres(params Type[] types) => Ddl(new PostgresProvider(), types);

  private static string TextOf(IReadOnlyList<DdlStatement> ddl, DdlKind kind, string objectName) =>
    ddl.Single(s => s.Kind == kind && s.ObjectName == objectName).Text;

  // ----- statements, not a script ----------------------------------------------------------------------------------

  // ----- ONE generated model, every shape of statement it produces -----------------------------------------------
  //
  // This was TEN methods over the same generated DDL — kinds, order, and the text of each statement — each calling
  // the generator again to assert one line of it. The five-vendor suite now RUNS this DDL and reads it back, so what
  // is left to check here is the text itself, and the text comes from one generation.
  [TestMethod]
  public void GeneratedDdl_IsOrderedKindedAndSpelled() {
    var ddl = Postgres();

    // ----- statements, not a script: each carries its kind and what it acts on, which is what lets the upgrade
    // order and interleave them later.
    Assert.IsTrue(ddl.Any(s => s.Kind == DdlKind.CreateSchema && s.ObjectName == "app"));
    Assert.IsTrue(ddl.Any(s => s.Kind == DdlKind.CreateTable && s.ObjectName == "Person"));
    Assert.IsTrue(ddl.Any(s => s.Kind == DdlKind.AddRefConstraint));

    // ----- in an order the database will accept: schemas before tables, tables before their keys, and reference
    // constraints LAST — a foreign key names another table, which has to exist by then.
    var lastTable = ddl.Select((s, i) => (s, i)).Last(x => x.s.Kind == DdlKind.CreateTable).i;
    var firstKey = ddl.Select((s, i) => (s, i)).First(x => x.s.Kind == DdlKind.AddPrimaryKey).i;
    var firstRef = ddl.Select((s, i) => (s, i)).First(x => x.s.Kind == DdlKind.AddRefConstraint).i;
    Assert.IsTrue(ddl.Select((s, i) => (s, i)).First(x => x.s.Kind == DdlKind.CreateSchema).i < lastTable);
    Assert.IsTrue(lastTable < firstKey);
    Assert.IsTrue(firstKey < firstRef);

    // ----- CREATE TABLE spells columns, types and nullability
    var person = TextOf(ddl, DdlKind.CreateTable, "Person");
    StringAssert.Contains(person, "CREATE TABLE \"app\".\"Person\" (");
    StringAssert.Contains(person, "  \"LastName\" varchar(80) NOT NULL");
    StringAssert.Contains(person, "  \"MiddleName\" varchar(50)");           // nullable: no NOT NULL
    Assert.IsFalse(person.Contains("\"MiddleName\" varchar(50) NOT NULL"));

    // ----- and identity is spelled by the DIALECT
    StringAssert.Contains(person, "\"Seq\" integer NOT NULL GENERATED BY DEFAULT AS IDENTITY");

    // ----- everything is quoted. ALWAYS, not "when needed" — unquoted identifiers break on a reserved word or a
    // folded case, and the exceptions are per-vendor.
    foreach (var statement in ddl.Where(s => s.Kind != DdlKind.Comment))
      StringAssert.Contains(statement.Text, "\"", statement.Text);

    // ----- columns are one per line and indented. Basic formatting costs nothing and helps on the day something
    // does go wrong.
    Assert.AreEqual(2,
      TextOf(ddl, DdlKind.CreateTable, "Address").Split('\n').Count(l => l.StartsWith("  \"")));

    // ----- the primary key is its own statement
    Assert.AreEqual(
      "ALTER TABLE \"app\".\"Person\" ADD CONSTRAINT \"PK_Person_Id\" PRIMARY KEY (\"Id\")",
      TextOf(ddl, DdlKind.AddPrimaryKey, "PK_Person_Id"));

    // ----- an index carries its order, its includes and its filter
    var index = TextOf(ddl, DdlKind.CreateIndex, "IX_Person_LastName_Rank");
    StringAssert.Contains(index, "CREATE INDEX \"IX_Person_LastName_Rank\" ON \"app\".\"Person\"");
    StringAssert.Contains(index, "(\"LastName\", \"Rank\" DESC)");
    StringAssert.Contains(index, " INCLUDE (\"City\")");
    StringAssert.Contains(index, " WHERE \"LastName\" IS NOT NULL");
    StringAssert.Contains(TextOf(ddl, DdlKind.CreateIndex, "UQ_Person_Email"), "CREATE UNIQUE INDEX");

    // ----- and a foreign key names both sides and its action
    var fk = ddl.Single(s => s.Kind == DdlKind.AddRefConstraint).Text;
    StringAssert.Contains(fk, "ALTER TABLE \"app\".\"Person\" ADD CONSTRAINT \"FK_Person_Address_Id\"");
    StringAssert.Contains(fk, "FOREIGN KEY (\"Address_Id\") REFERENCES \"app\".\"Address\" (\"Id\")");
    StringAssert.Contains(fk, " ON DELETE CASCADE");
  }

  // ----- the definition hash -----------------------------------------------------------------------------------------

  [TestMethod]
  public void Postgres_AttachesTheFilterHashSeparately() {
    // It regenerates and strips comments, so the hash cannot ride inside the statement — comparing our filter text
    // against what the server reports would report a difference on every startup.
    var comment = Postgres().Single(s => s.Kind == DdlKind.Comment);
    StringAssert.Contains(comment.Text, "COMMENT ON INDEX \"app\".\"IX_Person_LastName_Rank\" IS 'mic:h=");
  }

  [TestMethod]
  public void AServerThatPreservesCommentsNeedsNoSeparateHash() {
    var ddl = Ddl(new PreservingProvider(), typeof(IFilteredRow));
    Assert.AreEqual(0, ddl.Count(s => s.Kind == DdlKind.Comment));
  }

  [Index("Name", Filter = "\"Name\" IS NOT NULL")]
  private interface IFilteredRow {
    [PrimaryKey] Guid Id { get; set; }
    string Name { get; set; }
  }

  [TestMethod]
  public void Hash_IsDeterministicAndFollowsTheDefinition() {
    // It is persisted and compared across processes and machines, so a randomly seeded hash would report every object
    // as changed after a restart.
    Assert.AreEqual(DefinitionHashHelper.Of("a = 1"), DefinitionHashHelper.Of("a = 1"));
    Assert.AreNotEqual(DefinitionHashHelper.Of("a = 1"), DefinitionHashHelper.Of("a = 2"));
    StringAssert.StartsWith(DefinitionHashHelper.Of("x"), "mic:h=");
  }

  // ----- what a dialect costs a provider ------------------------------------------------------------------------------

  /// <summary>A SQL-Server-shaped server: bracket quoting and a different identity clause — assigned, not overridden.</summary>
  private class BracketProvider : ModelOnlyProvider {
    public BracketProvider() : base(DbServerKind.MsSql, BuildTypeRegistry(), new SqlDialect {
      QuoteLeft = "[",
      QuoteRight = "]",
      QuoteEscape = "]]",
      Identity = " IDENTITY(1,1)",
    }) { }
    public override DbFeatures Features =>
      DbFeatures.Schemas | DbFeatures.ReferentialConstraints | DbFeatures.FilterInIndexes
      | DbFeatures.ServerPreservesComments | DbFeatures.IdentityColumns | DbFeatures.NamedRefConstraints
      | DbFeatures.FullAlterTable;
    public override string DefaultSchema => "dbo";

    private static DbTypeRegistry BuildTypeRegistry() {
      var registry = new DbTypeRegistry();
      registry.Add("nvarchar", typeof(string), DbTypeFlags.TakesSize, specialType: DbSpecialType.String);
      registry.Add("uniqueidentifier", typeof(Guid));
      registry.Add("int", typeof(int));
      return registry;
    }
  }

  private interface ISimpleRow {
    [PrimaryKey] Guid Id { get; set; }
    string Name { get; set; }
    [Auto(AutoType.Identity)] int Seq { get; set; }
  }

  private sealed class PreservingProvider : BracketProvider { }

  [TestMethod]
  public void ADialectIsASSIGNEDNotOverridden() {
    // The whole vendor difference here is four template values. No method was overridden to spell any of it.
    var text = TextOf(Ddl(new BracketProvider(), typeof(ISimpleRow)), DdlKind.CreateTable, "SimpleRow");

    StringAssert.Contains(text, "CREATE TABLE [app].[SimpleRow] (");
    StringAssert.Contains(text, "[Name] nvarchar(50) NOT NULL");
    StringAssert.Contains(text, "[Seq] int NOT NULL IDENTITY(1,1)");
  }

  [TestMethod]
  public void Postgres_OverridesNoTemplate() {
    // The defaults are standard SQL, so a provider that follows the standard assigns nothing — which is the measure
    // of whether the base really implements the maximum.
    var standard = new SqlDialect();
    var postgres = new PostgresProvider().SqlDialect;

    Assert.AreEqual(standard.QuoteLeft, postgres.QuoteLeft);
    Assert.AreEqual(standard.Identity, postgres.Identity);
    Assert.AreEqual(standard.CreateTable, postgres.CreateTable);
    Assert.AreEqual(standard.AddRefConstraint, postgres.AddRefConstraint);
  }

  [TestMethod]
  public void UnmanagedSchema_IsNeverCreated() {
    // Attaching to a database whose schemas belong to somebody else is the normal case in the legacy and migration
    // scenarios; such a schema must never attract a CREATE.
    var app = new EntityApp("App", new Version(1, 0), new EntityAppSettings { DefaultSchema = "legacy" });
    var module = new EntityModule("M", new Version(1, 0));
    module.RegisterEntities(typeof(IAddress));
    app.AddModule(module);
    app.Settings.IncludeDbInfoModule = false;
    app.TryInit();
    app.Model!.FindSchema("legacy")!.IsManaged = false;
    AppInitHelper.CreateDatabase(app, new DbSettings(new PostgresProvider(), NoServer));

    var ddl = new DbDdlBuilder(new PostgresProvider()).CreateModel(app.MappedModel());
    Assert.AreEqual(0, ddl.Count(s => s.Kind == DdlKind.CreateSchema));
    Assert.IsTrue(ddl.Any(s => s.Kind == DdlKind.CreateTable));      // the tables in it are still created
  }
}
